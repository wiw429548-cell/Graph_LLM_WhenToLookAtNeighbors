def jl(p):
    try:
        return json.load(open(p, encoding="utf-8")) if Path(p).exists() else None
    except (OSError, ValueError):
        return None


def f(x, d=3):
    if x is None:
        return NA
    try:
        x = float(x)
    except (TypeError, ValueError):
        return NA
    return NA if x != x else f"{x:.{d}f}"


def at(curve, b, key="acc"):
    if not curve:
        return None
    for c in curve["curve"]:
        if abs(c["budget"] - b) < 1e-9:
            return c[key]
    return None


def tex_escape(s):
    return str(s).replace("_", "\\_").replace("%", "\\%").replace("&", "\\&").replace("#", "\\#")


class Table:
    def __init__(self, name, title, header, caption=None):
        self.name, self.title, self.header, self.caption, self.rows = name, title, header, caption or title, []

    def add(self, row):
        self.rows.append([str(x) for x in row])

    def md(self):
        if not self.rows:
            return [f"### {self.title}", "", "(no results yet)", ""]
        strip = lambda s: (s.replace("$\\pm$", "±").replace("\\times", "×").replace("\\hat", "").replace("\\Pi", "Π")
                           .replace("\\tau", "τ").replace("\\Delta", "Δ").replace("\\textbf{", "").replace("}", "")
                           .replace("{", "").replace("$", "").replace("\\", ""))
        return ([f"### {self.title}", "", "| " + " | ".join(strip(h) for h in self.header) + " |",
                 "|" + "---|" * len(self.header)] + ["| " + " | ".join(strip(c) for c in r) + " |" for r in self.rows]
                + [""])

    def tex(self):
        # cells with LaTeX markup are kept verbatim except for bare '%' (would comment out the rest of the row)
        raw = lambda s: re.sub(r"(?<!\\)%", r"\\%", s)
        hdr = [raw(h) if ("$" in h or "\\" in h) else tex_escape(h) for h in self.header]
        body = [" & ".join(tex_escape(c) if not ("$" in c or "\\" in c) else raw(c) for c in r) + " \\\\"
                for r in self.rows]
        return "\n".join(["% auto-generated by needn/aggregate.py -- do not edit", "\\begin{table*}[t]", "\\centering",
                          "\\small", f"\\caption{{{tex_escape(self.caption)}}}", f"\\label{{tab:{self.name}}}",
                          "\\resizebox{\\textwidth}{!}{%", "\\begin{tabular}{l" + "c" * (len(self.header) - 1) + "}",
                          "\\toprule", " & ".join(hdr) + " \\\\", "\\midrule", *body, "\\bottomrule", "\\end{tabular}}",
                          "\\end{table*}", ""])

    def write(self):
        (R / "latex").mkdir(parents=True, exist_ok=True)
        (R / "latex" / f"{self.name}.tex").write_text(self.tex(), encoding="utf-8")


def mean_row(table, label="Average", skip=1):
    cols = list(zip(*table.rows)) if table.rows else []
    out = [label] + [""] * (skip - 1)  # columns 1..skip-1 (e.g. homophily) are not averaged
    for j in range(skip, len(table.header)):
        vals, ints = [], True
        for v in (cols[j] if j < len(cols) else []):
            try:
                vals.append(float(v.split()[0]))
                ints = ints and "." not in v.split()[0]
            except (ValueError, IndexError):
                pass
        ok = vals and len(vals) == len(table.rows)
        out.append((f"{np.mean(vals):.0f}" if ints else f"{np.mean(vals):.3f}") if ok else NA)
    return out


def wilcoxon(a, b):
    from scipy.stats import wilcoxon as w
    pairs = [(x, y) for x, y in zip(a, b) if x is not None and y is not None]
    if len(pairs) < 5:
        return None, len(pairs), None
    d = np.array([x - y for x, y in pairs])
    if np.all(d == 0):
        return 1.0, len(pairs), 0.0
    return float(w(d).pvalue), len(pairs), float(d.mean())


def engine_notes():
    p = R / "engine_log.jsonl"
    if not p.exists():
        return ["(no vLLM engine log: HF backend or no LLM run yet)"]
    out = []
    for line in p.read_text(encoding="utf-8").splitlines():
        try:
            e = json.loads(line)
        except ValueError:
            continue
        if e.get("fallback"):
            out.append(f"- {e.get('time')}: {e.get('model')} tp={e.get('tp')}/{e.get('tp_requested')} "
                       f"max_model_len={e.get('max_model_len')} eager={e.get('enforce_eager')} attempt={e.get('attempt')} "
                       f"({e.get('argv', '')[-120:]})")
    return out or ["- none: every vLLM engine started with the planned configuration"]


def llm_extra_tables(m, dss, A, cfg, tables):
    """reviewer-requested analyses: LLM+GNN baselines, per-node gain breakdown, local-homophily strata"""
    t = Table(f"llmgnn_{m}", f"Training-free LLM+GNN combinations ({m})",
              ["Dataset", "f0 (text)", "GCN", "f0+GCN ens.", "NeedNbr-TF@20% (CNS)", "NeedNbr-TF@20% $\\to$ GCN",
               "GraphICL", "f1 CNS (all)"],
              caption=f"LLM+GNN baselines without extra LLM calls ({m}): GCN on frozen embeddings with 20 labels per "
                      f"class (mean probabilities of 5 seeds), the average of f0 and GCN probabilities, and a cascade that "
                      f"answers the NeedNbr-routed 20% with the GCN instead of a graph-augmented prompt.")
    for d in dss:
        r = A[(m, d)]
        lg = r.get("llm_gnn") or {}
        t.add([d, f(r["acc_f0"]), f(lg.get("acc_gcn")), f(lg.get("acc_f0_gcn_ensemble")),
               f(at(r["curves"].get(f"cns|{TF}"), .2)), f(lg.get("acc_needNbr20_to_gcn")),
               f(r["acc_f1_full"].get("graphicl")), f(r["acc_f1_full"].get("cns"))])
    if t.rows:
        t.add(mean_row(t))
    tables.append(t)
    t = Table(f"gain_{m}", f"Per-node effect of neighbours ({m}): share of test nodes helped / hurt",
              ["Dataset", "random +/-", "SNS +/-", "CNS +/-", "GraphICL +/-", "any fixes",
               "CNS helped in top-20%", "CNS hurt in top-20%"],
              caption=f"Per-node gain breakdown ({m}): '+' = share of test nodes that f0 gets wrong and f1 right, '-' = "
                      f"the reverse; any fixes = share of nodes fixed by at least one strategy; the last two columns give "
                      f"the share of the CNS-helped / CNS-hurt nodes that NeedNbr-TF routes at a 20% budget (random "
                      f"routing: 0.20).")
    for d in dss:
        gb = A[(m, d)].get("gain_breakdown") or {}
        pm = lambda s_: f"{f(gb[s_]['helped'], 2)} / {f(gb[s_]['hurt'], 2)}" if s_ in gb else NA
        t.add([d, pm("random"), pm("similar"), pm("cns"), pm("graphicl"), f(gb.get("_any_strategy_fixes"), 2),
               f((gb.get("cns") or {}).get("helped_in_routed20"), 2), f((gb.get("cns") or {}).get("hurt_in_routed20"), 2)])
    tables.append(t)
    # local homophily strata, pooled over datasets (node-weighted); all datasets and heterophilic datasets only
    cols = ["acc_f0", "acc_f1_random", "acc_f1_similar", "acc_f1_cns", "acc_f1_graphicl", "acc_needNbr20", "routed_frac"]
    t = Table(f"homstrata_{m}", f"Accuracy by local homophily of the test node ({m}), pooled over datasets",
              ["Group", "local $h$", "#nodes", "f0", "f1 random", "f1 SNS", "f1 CNS", "GraphICL", "NeedNbr-TF@20%",
               "routed frac."],
              caption=f"Accuracy by the test node's local homophily (share of 1-hop neighbours with its label; true labels, "
                      f"analysis only) ({m}), node-weighted over the datasets of each group; '--' = strategy not run on "
                      f"every dataset contributing to the bin.")
    for grp, sel in (("all", dss), ("heterophilic", [d for d in dss if cfg["datasets"][d].get("hetero")]),
                     ("homophilic", [d for d in dss if not cfg["datasets"][d].get("hetero")])):
        bins = {}
        for d in sel:
            for row in A[(m, d)].get("by_local_homophily") or []:
                bins.setdefault(row["bin"], []).append(row)
        for b in sorted(bins, key=lambda x: (x != "isolated", x)):
            rows = bins[b]
            n = sum(r_["n"] for r_ in rows)
            vals = [np.sum([r_[c_] * r_["n"] for r_ in rows]) / n if all(c_ in r_ for r_ in rows) else None
                    for c_ in cols]
            t.add([grp, b, n] + [f(v) for v in vals])
    tables.append(t)
    t = Table(f"homophily_{m}", f"Dataset homophily vs. effect of neighbours ({m})",
              ["Dataset", "$h$ (edge)", "$h_{adj}$", "$\\Delta$ f1 random", "$\\Delta$ f1 CNS", "$\\Delta$ NeedNbr-TF@20%"])
    for d in dss:
        r = A[(m, d)]
        dl = lambda x: None if x is None else x - r["acc_f0"]
        t.add([d, f(r["homophily"], 2), f(r.get("adj_homophily"), 2), f(dl(r["acc_f1_full"].get("random"))),
               f(dl(r["acc_f1_full"].get("cns"))), f(dl(at(r["curves"].get(f"cns|{TF}"), .2)))])
    tables.append(t)


